CREATE PROCEDURE SP_PLACE_ORDER (
  IN  P_CUSTNO         CHAR(6),
  IN  P_ORDER_NO       CHAR(8),
  IN  P_PAYMENT_METHOD VARCHAR(20),
  IN  P_SUBTOTAL       DECIMAL(11,2),
  OUT P_ORDER_ID       INTEGER,
  OUT P_TOTAL_AMOUNT   DECIMAL(11,2)
)
LANGUAGE SQL
MODIFIES SQL DATA
BEGIN
  DECLARE V_CUST_EXISTS INTEGER DEFAULT 0;--
  DECLARE V_TAX         DECIMAL(9,2) DEFAULT 0.00;--
  DECLARE V_FREIGHT     DECIMAL(9,2) DEFAULT 15.00;--
  DECLARE V_STATE       CHAR(2);--
  DECLARE CUST_MISSING  CONDITION FOR SQLSTATE '75002';--

  DECLARE EXIT HANDLER FOR NOT FOUND
    SIGNAL CUST_MISSING SET MESSAGE_TEXT = 'Customer does not exist in CUSTOMERS table';--

  SELECT STATE INTO V_STATE
    FROM CUSTOMERS
   WHERE CUSTNO = P_CUSTNO;--

  -- Apply 6% tax for TX, 7% for CA/NY
  IF V_STATE = 'TX' THEN
    SET V_TAX = ROUND(P_SUBTOTAL * 0.06, 2);--
  ELSEIF V_STATE IN ('CA', 'NY') THEN
    SET V_TAX = ROUND(P_SUBTOTAL * 0.07, 2);--
  ELSE
    SET V_TAX = 0.00;--
  END IF;--

  SET P_TOTAL_AMOUNT = P_SUBTOTAL + V_TAX + V_FREIGHT;--

  INSERT INTO ORDERS (
    ORDER_NO,
    CUSTNO,
    ORDER_DATE,
    REQUIRED_DATE,
    STATUS,
    SUBTOTAL,
    TAX_AMOUNT,
    FREIGHT_CHARGE,
    TOTAL_AMOUNT,
    PAYMENT_METHOD,
    PAYMENT_STATUS
  ) VALUES (
    P_ORDER_NO,
    P_CUSTNO,
    CURRENT DATE,
    CURRENT DATE + 7 DAYS,
    'PENDING',
    P_SUBTOTAL,
    V_TAX,
    V_FREIGHT,
    P_TOTAL_AMOUNT,
    P_PAYMENT_METHOD,
    'AUTHORIZED'
  );--

  SELECT ORDER_ID INTO P_ORDER_ID
    FROM ORDERS
   WHERE ORDER_NO = P_ORDER_NO;--

END;--
;

