CREATE VIEW V_MONTHLY_SALES AS
SELECT YEAR(INVDATE) AS SALES_YEAR,
       MONTH(INVDATE) AS SALES_MONTH,
       COUNT(*) AS INVOICE_COUNT,
       SUM(INVTOTAL) AS TOTAL_SALES,
       AVG(INVTOTAL) AS AVG_INVOICE
