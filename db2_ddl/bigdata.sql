CREATE PROCEDURE SP_CHECK_INVENTORY_SHORTAGE (
  OUT P_CRITICAL_ITEMS_COUNT INTEGER,
  OUT P_TOTAL_UNITS_DEFICIT  INTEGER
)
LANGUAGE SQL
MODIFIES SQL DATA
BEGIN
  DECLARE V_ON_HAND      INTEGER;--
  DECLARE V_ALLOCATED    INTEGER;--
  DECLARE V_REORDER_PT   INTEGER;--
  DECLARE V_AVAIL        INTEGER;--
  DECLARE V_AT_END       SMALLINT DEFAULT 0;--

  DECLARE C_SHORTAGE CURSOR FOR
    SELECT ON_HAND_QTY, ALLOCATED_QTY, REORDER_POINT
      FROM INVENTORY
     WHERE (ON_HAND_QTY - ALLOCATED_QTY) < REORDER_POINT;--

  DECLARE CONTINUE HANDLER FOR NOT FOUND
    SET V_AT_END = 1;--

  SET P_CRITICAL_ITEMS_COUNT = 0;--
  SET P_TOTAL_UNITS_DEFICIT  = 0;--

  OPEN C_SHORTAGE;--
  FETCH C_SHORTAGE INTO V_ON_HAND, V_ALLOCATED, V_REORDER_PT;--

  WHILE V_AT_END = 0 DO
    SET V_AVAIL = V_ON_HAND - V_ALLOCATED;--
    SET P_CRITICAL_ITEMS_COUNT = P_CRITICAL_ITEMS_COUNT + 1;--
    SET P_TOTAL_UNITS_DEFICIT  = P_TOTAL_UNITS_DEFICIT + (V_REORDER_PT - V_AVAIL);--

    FETCH C_SHORTAGE INTO V_ON_HAND, V_ALLOCATED, V_REORDER_PT;--
  END WHILE;--

  CLOSE C_SHORTAGE;--
END;--;

